void boot(int model, const std::vector<uint8_t>& flashImage, SerialSink sink) {
  // setup() never touches these, so a second boot (a model switch) clears them like tests/mocks.cpp does
  if (userFirmwareActive) changeUserFirmwareMode(false);
  stopMidiTextScroll();
  midiTextAppend(0);
  midiTextFont = 2;
  midiCellColCC = 0;
  midiCellRowCC = 0;
  controlModeActive = false;
  controlButton = -1;

  host::reset();
  host::useRealClock(true);
  host::setSerialSink(sink);
  host::setPin(38, model == 200 ? HIGH : LOW);

  bool fresh = flashImage.size() != LINN_FAKE_FLASH_SIZE;
  if (fresh) {
    dueFlashStorage.erase();
    // a boot block of 255 means "just flashed" and starts serial mode; any other value
    // starts MIDI mode with default settings, as after the Updater restored them
    dueFlashStorage.write(0, 1);
  }
  else {
    memcpy(dueFlashStorage.storage, flashImage.data(), LINN_FAKE_FLASH_SIZE);
  }

  setup();

  if (fresh) {
    controlButton = -1;
    setDisplayMode(displayNormal);
    updateDisplay();
    storeSettings();
  }
}

