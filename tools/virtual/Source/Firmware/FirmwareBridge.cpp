Led led(int col, int row) {
  Led result = { 0, 0 };
  if (col < 0 || col >= NUMCOLS || row < 0 || row >= NUMROWS) return result;
  byte data = ledVisible(LED_LAYER_COMBINED, col, row);
  result.color = (data & B11111000) >> 3;
  result.display = data & B00000111;
  return result;
}

// the LED driver keeps these rhythms in statics of its own, so they are mirrored here
bool pulseOn(int display) {
  switch (display) {
    case fastPulse: return (millis() / 80) % 2 == 0;
    case slowPulse: return (millis() / 120) % 2 == 0;
    case focusPulse: return clock24PPQ >= 6;
  }
  return display == on;
}

uint16_t rawX(int col, float fraction) {
  if (col < 1) return (uint16_t)FXD_TO_INT(FXD_CALX_DEFAULT_LEFT_EDGE);
  int width = FXD_TO_INT(FXD_CALX_DEFAULT_CELL_WIDTH);
  int first = FXD_TO_INT(FXD_CALX_DEFAULT_FIRST_CELL);
  int x = first + (col - 1) * width + (int)(fraction * width);
  if (x < 0) x = 0;
  if (x > 4095) x = 4095;
  return (uint16_t)x;
}

uint16_t rawY(int row, float fraction) {
  if (row < 0 || row >= NUMROWS) return 0;
  int low = CALY_DEFAULT_MIN[row];
  int high = CALY_DEFAULT_MAX[row];
  return (uint16_t)(low + (int)(fraction * (high - low)));
}

